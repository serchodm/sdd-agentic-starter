#!/usr/bin/env python3
"""
SDD Framework Bi-Directional Synchronizer (sdd_sync.py)
Permite mantener sincronizado el framework agentico (catalogo inerte, reglas core,
skills, scripts, estandares, workflows) entre proyectos derivados y el repositorio plantilla (sdd-agentic-starter).

Enforces:
- Protege la plantilla contra contaminacion de proyectos derivados.
- Nunca sube ficheros generados (cabecera GENERATED) ni `.agents/overrides/`.
- Sincroniza bidireccionalmente el catalogo inerte `.sdd/catalog/`.
"""

import argparse
import filecmp
import json
import os
import pathlib
import shutil
import sys

# Compatibilidad UTF-8 en Windows
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except (AttributeError, OSError, ValueError) as exc:
        print(f"[WARN] No se pudo configurar salida UTF-8: {exc}", file=sys.stderr)

# Componentes exactos que forman el "Core y Catalogo del Framework"
FRAMEWORK_PATHS = [
    ".sdd/catalog",
    ".agents/scripts",
    ".agents/contexts",
    ".agents/workflows",
    ".agents/hooks.json",
    ".github/workflows",
    ".githooks",
    "scripts",
    "docs/standards",
    "specs/templates",
    "specs/SDD_FRAMEWORK.md",
]

# Core agents que si son parte fija del starter
CORE_AGENT_FILES = {
    ".agents/agents/orchestrator.md",
    ".agents/agents/functional-analyst.md",
    ".agents/agents/architect.md",
    ".agents/agents/qa-tester.md",
    ".agents/agents/documentator.md",
    ".agents/agents/devops.md",
}

# Core rules fijas del starter
CORE_RULE_PREFIXES = (
    ".agents/rules/00-",
    ".agents/rules/01-",
    ".agents/rules/02-",
    ".agents/rules/03-",
    ".agents/rules/04-",
    ".agents/rules/05-",
    ".agents/rules/06-",
    ".agents/rules/07-",
)

EXCLUDE_EXACT = {
    ".agents/ACTIVE_STATE.md",
    ".agents/active_work_item.json",
    ".agents/squad.lock.json",
}

DEFAULT_TEMPLATE_PATH = pathlib.Path("C:/Projects/sdd-agentic-starter")
GENERATED_MARKER = "GENERATED by sdd_agent_generator"
GENERATED_PREVIEW_CHARS = 4096
LOCK_REL_PATH = pathlib.Path(".agents") / "squad.lock.json"


def _normalize_rel_path(rel_path: str) -> str:
    norm = rel_path.replace("\\", "/")
    if norm.startswith("./"):
        norm = norm[2:]
    return norm


def load_managed_lock_paths(base_dir: pathlib.Path) -> set[str]:
    """Load relative file paths managed in `.agents/squad.lock.json['files']`."""
    lock_path = base_dir / LOCK_REL_PATH
    if not lock_path.exists():
        return set()
    try:
        payload = json.loads(lock_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        print(f"[WARN] No se pudo leer '{lock_path}': {exc}", file=sys.stderr)
        return set()

    if not isinstance(payload, dict):
        print(
            f"[WARN] Formato invalido en '{lock_path}': se esperaba objeto JSON.",
            file=sys.stderr,
        )
        return set()

    files_entry = payload.get("files")
    if files_entry is None:
        return set()
    if not isinstance(files_entry, dict):
        print(
            f"[WARN] Formato invalido en '{lock_path}': 'files' debe ser un objeto.",
            file=sys.stderr,
        )
        return set()

    return {
        _normalize_rel_path(key)
        for key in files_entry
        if isinstance(key, str) and key.strip()
    }


def _infer_base_dir(rel_path: str, file_path: pathlib.Path) -> pathlib.Path | None:
    parts = pathlib.PurePosixPath(rel_path).parts
    if not parts or "." in parts or ".." in parts or len(file_path.parts) < len(parts):
        return None
    if file_path.parts[-len(parts) :] != parts:
        return None
    return file_path.parents[len(parts) - 1]


def is_syncable_framework_file(
    rel_path: str,
    file_path: pathlib.Path,
    managed_lock_paths: set[str] | None = None,
) -> bool:
    """Return True if rel_path belongs to core framework and is not generator-managed."""
    norm_rel = _normalize_rel_path(rel_path)
    if norm_rel in EXCLUDE_EXACT:
        return False
    if norm_rel.startswith(".agents/overrides/"):
        return False
    if norm_rel.endswith(".pyc") or "__pycache__" in norm_rel:
        return False

    effective_lock_paths = managed_lock_paths
    if effective_lock_paths is None:
        inferred_root = _infer_base_dir(norm_rel, file_path)
        effective_lock_paths = (
            load_managed_lock_paths(inferred_root) if inferred_root is not None else set()
        )
    if norm_rel in effective_lock_paths:
        return False

    # Never sync generated files back to template
    if file_path.exists():
        try:
            with file_path.open("r", encoding="utf-8", errors="ignore") as handle:
                content_preview = handle.read(GENERATED_PREVIEW_CHARS)
            if GENERATED_MARKER in content_preview:
                return False
        except OSError as exc:
            print(f"[WARN] No se pudo inspeccionar '{file_path}': {exc}", file=sys.stderr)

    # Direct match in framework paths
    for base in FRAMEWORK_PATHS:
        if norm_rel == base or norm_rel.startswith(f"{base}/"):
            return True

    # Check core agents
    if norm_rel in CORE_AGENT_FILES:
        return True

    # Check core rules
    if any(norm_rel.startswith(prefix) for prefix in CORE_RULE_PREFIXES):
        return True

    # Check core skills
    if norm_rel.startswith(".agents/skills/"):
        return True

    return False


def get_all_framework_files(base_dir: pathlib.Path) -> set[str]:
    """Collect all syncable framework-relative paths under base_dir."""
    managed_lock_paths = load_managed_lock_paths(base_dir)
    files: set[str] = set()
    for root, _, filenames in os.walk(base_dir):
        for fname in filenames:
            full_path = pathlib.Path(root) / fname
            rel = full_path.relative_to(base_dir).as_posix()
            if is_syncable_framework_file(
                rel, full_path, managed_lock_paths=managed_lock_paths
            ):
                files.add(rel)
    return files


def compare_framework(source_root: pathlib.Path, template_root: pathlib.Path) -> None:
    src_files = get_all_framework_files(source_root)
    tpl_files = get_all_framework_files(template_root)
    all_files = sorted(src_files | tpl_files)

    identical = []
    modified = []
    only_in_source = []
    only_in_template = []

    for rel in all_files:
        f_src = source_root / rel
        f_tpl = template_root / rel

        if f_src.exists() and f_tpl.exists():
            if filecmp.cmp(f_src, f_tpl, shallow=False):
                identical.append(rel)
            else:
                modified.append(rel)
        elif f_src.exists() and not f_tpl.exists():
            only_in_source.append(rel)
        elif not f_src.exists() and f_tpl.exists():
            only_in_template.append(rel)

    print("=== ESTADO DE SINCRONIZACION DEL FRAMEWORK SDD ===")
    print(f"Origen (Proyecto Actual): {source_root}")
    print(f"Destino (Plantilla SDD) : {template_root}\n")

    if modified:
        print("[MODIFICADOS / DIVERGENTES]:")
        for f in modified:
            print(f"  * {f}")
        print()

    if only_in_source:
        print("[NUEVOS EN ESTE PROYECTO (Candidatos para subir al catalogo/framework)]:")
        for f in only_in_source:
            print(f"  + {f}")
        print()

    if only_in_template:
        print("[SOLO EN LA PLANTILLA (Candidatos para incorporar al proyecto)]:")
        for f in only_in_template:
            print(f"  - {f}")
        print()

    if not modified and not only_in_source and not only_in_template:
        print("[OK] Todos los componentes del framework estan 100% sincronizados.\n")
    else:
        print(
            f"Total: {len(identical)} identicos, {len(modified)} modificados, "
            f"{len(only_in_source)} solo en proyecto, {len(only_in_template)} solo en plantilla.\n"
        )


def push_to_template(source_root: pathlib.Path, template_root: pathlib.Path) -> None:
    print(f"Sincronizando mejoras del Framework: {source_root} -> {template_root}")
    src_files = get_all_framework_files(source_root)
    copied = 0

    for rel in sorted(src_files):
        src_file = source_root / rel
        dst_file = template_root / rel
        dst_file.parent.mkdir(parents=True, exist_ok=True)

        content = src_file.read_bytes()
        try:
            text = content.decode("utf-8")
            # Extra shield against project-specific local names
            sanitized = (
                text.replace("P.A.C.O.", "Project")
                .replace("PACO", "Project")
                .replace("@jarvis", "@orchestrator")
            )
            content = sanitized.encode("utf-8")
        except UnicodeDecodeError:
            pass

        if not dst_file.exists() or dst_file.read_bytes() != content:
            dst_file.write_bytes(content)
            copied += 1
            print(f"  -> Exportado: {rel}")

    print(f"\n[OK] Sincronizacion completada: {copied} fichero(s) actualizados en la plantilla.")


def pull_from_template(source_root: pathlib.Path, template_root: pathlib.Path) -> None:
    print(f"Incorporando mejoras de la Plantilla al Proyecto: {template_root} -> {source_root}")
    tpl_files = get_all_framework_files(template_root)
    copied = 0

    for rel in sorted(tpl_files):
        src_file = template_root / rel
        dst_file = source_root / rel
        dst_file.parent.mkdir(parents=True, exist_ok=True)

        content = src_file.read_bytes()
        if not dst_file.exists() or dst_file.read_bytes() != content:
            dst_file.write_bytes(content)
            copied += 1
            print(f"  <- Incorporado: {rel}")

    print(f"\n[OK] Actualizacion completada: {copied} fichero(s) incorporados desde la plantilla.")


def main() -> None:
    parser = argparse.ArgumentParser(description="SDD Framework Bi-Directional Synchronizer")
    parser.add_argument(
        "--template-dir",
        type=str,
        default=str(DEFAULT_TEMPLATE_PATH),
        help="Ruta hacia el repositorio de la plantilla SDD",
    )
    group = parser.add_mutually_exclusive_group(required=False)
    group.add_argument(
        "--status",
        action="store_true",
        help="Muestra la divergencia y estado entre proyecto y plantilla",
    )
    group.add_argument(
        "--push-to-template",
        type=str,
        metavar="PATH",
        help="Exporta las mejoras del framework al repositorio plantilla",
    )
    group.add_argument(
        "--pull-from-template",
        type=str,
        metavar="PATH",
        help="Incorpora las mejoras de la plantilla a este proyecto",
    )

    args = parser.parse_args()
    current_root = pathlib.Path(__file__).resolve().parents[1]
    template_root = pathlib.Path(args.template_dir).resolve()

    if args.push_to_template:
        push_to_template(current_root, pathlib.Path(args.push_to_template).resolve())
    elif args.pull_from_template:
        pull_from_template(current_root, pathlib.Path(args.pull_from_template).resolve())
    else:
        compare_framework(current_root, template_root)


if __name__ == "__main__":
    main()
