#!/usr/bin/env python3
"""SDD Framework Bi-Directional Synchronizer (`sdd_sync.py`).

Synchronizes core framework artifacts between derived projects and an explicit
template repository (`--template-dir` / `SDD_TEMPLATE_DIR`) with fail-closed
conflict detection, `--dry-run` planning, symlink escape guards, and staging
backup + transactional rollback.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, replace
import filecmp
import hashlib
import json
import os
import pathlib
import shutil
import stat
import sys
import tempfile

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError, ValueError) as exc:
        print(f"[WARN] No se pudo configurar salida UTF-8: {exc}", file=sys.stderr)

FRAMEWORK_PATHS = [
    ".sdd/catalog", ".agents/scripts", ".agents/contexts", ".agents/workflows",
    ".agents/hooks.json", ".github/workflows", ".githooks", "scripts",
    "docs/standards", "specs/templates", "specs/SDD_FRAMEWORK.md",
]
CORE_AGENT_FILES = {
    ".agents/agents/orchestrator.md", ".agents/agents/functional-analyst.md",
    ".agents/agents/architect.md", ".agents/agents/qa-tester.md",
    ".agents/agents/documentator.md", ".agents/agents/devops.md",
}
CORE_RULE_PREFIXES = tuple(f".agents/rules/0{i}-" for i in range(8))
EXCLUDE_EXACT = {
    ".agents/ACTIVE_STATE.md", ".agents/active_work_item.json",
    ".agents/squad.lock.json", ".agents/.sdd-sync-state.json",
}
GENERATED_MARKER = "GENERATED by sdd_agent_generator"
GENERATED_PREVIEW_CHARS = 4096
LOCK_REL_PATH = pathlib.Path(".agents") / "squad.lock.json"
SYNC_STATE_REL_PATH = pathlib.Path(".agents") / ".sdd-sync-state.json"
TEMPLATE_DIR_ENV_VAR = "SDD_TEMPLATE_DIR"
IGNORED_WALK_DIRS = frozenset({".git", ".worktrees", ".venv", "venv", "node_modules", "__pycache__"})
_REPARSE_ATTR = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x0400)


class SddSyncError(RuntimeError):
    """Base fail-closed error for SDD synchronization."""


class SyncConfigError(SddSyncError):
    """Raised when template or source configuration is missing or invalid."""


class SyncSecurityError(SddSyncError):
    """Raised when a symlink escape, reparse point, or traversal is detected."""


class SyncConflictError(SddSyncError):
    """Raised when destination diverges from synced baseline without `--force`."""


@dataclass(frozen=True)
class SyncPlan:
    """Computed synchronization plan and execution outcome."""

    direction: str
    source_root: pathlib.Path
    target_root: pathlib.Path
    added: tuple[str, ...]
    updated: tuple[str, ...]
    conflicts: tuple[str, ...]
    skipped: tuple[str, ...]
    applied: bool = False
    dry_run: bool = False


def _normalize_rel_path(rel_path: str) -> str:
    norm = rel_path.replace("\\", "/")
    return norm[2:] if norm.startswith("./") else norm


def _is_reparse_or_symlink(path: pathlib.Path) -> bool:
    try:
        st = path.lstat()
    except FileNotFoundError:
        return False
    except OSError:
        return True
    if stat.S_ISLNK(st.st_mode):
        return True
    return os.name == "nt" and bool(getattr(st, "st_file_attributes", 0) & _REPARSE_ATTR)


def _validate_root_dir(raw_path: str | pathlib.Path, label: str) -> pathlib.Path:
    candidate = pathlib.Path(raw_path)
    if _is_reparse_or_symlink(candidate):
        raise SyncSecurityError(f"{label} must not be a symlink or reparse point: {candidate}")
    if not candidate.exists() or not candidate.is_dir():
        raise SyncConfigError(f"{label} does not exist or is not a directory: {candidate}")
    resolved = candidate.resolve()
    if _is_reparse_or_symlink(resolved):
        raise SyncSecurityError(f"Resolved {label} must not be a symlink or reparse point: {resolved}")
    return resolved


def resolve_template_root(
    template_arg: str | pathlib.Path | None = None, *, source_root: pathlib.Path | None = None
) -> pathlib.Path:
    """Resolve and validate template repository strictly from explicit arg or env."""
    raw = str(template_arg).strip() if template_arg is not None else ""
    if not raw:
        raw = os.environ.get(TEMPLATE_DIR_ENV_VAR, "").strip()
    if not raw:
        raise SyncConfigError(f"Missing template directory: pass --template-dir or set {TEMPLATE_DIR_ENV_VAR}.")
    resolved = _validate_root_dir(raw, "Template directory")
    if source_root is not None and resolved == _validate_root_dir(source_root, "Source directory"):
        raise SyncConfigError(f"Source and template directories must be distinct: {resolved}")
    return resolved


def _resolve_safe_member(root: pathlib.Path, rel_path: str) -> pathlib.Path:
    if not rel_path or "\\" in rel_path or rel_path.startswith("/"):
        raise SyncSecurityError(f"Unsafe relative sync path: {rel_path!r}")
    pure = pathlib.PurePosixPath(rel_path)
    parts = pure.parts
    if not parts or pure.is_absolute() or any(p in {"", ".", ".."} or ":" in p for p in parts):
        raise SyncSecurityError(f"Invalid relative sync path: {rel_path!r}")
    root_resolved = root.resolve()
    cur = root_resolved
    for part in parts:
        cur = cur / part
        if _is_reparse_or_symlink(cur):
            raise SyncSecurityError(f"Symlink/reparse point not permitted in sync path: {rel_path}")
    resolved = cur.resolve(strict=False)
    if not resolved.is_relative_to(root_resolved) or resolved == root_resolved:
        raise SyncSecurityError(f"Sync path escapes workspace root: {rel_path}")
    return cur


def load_managed_lock_paths(base_dir: pathlib.Path) -> set[str]:
    """Load relative file paths managed in `.agents/squad.lock.json['files']`."""
    lock_path = base_dir / LOCK_REL_PATH
    if not lock_path.exists():
        return set()
    try:
        payload = json.loads(lock_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        print(f"[WARN] No se pudo leer '{lock_path}': {exc}", file=sys.stderr)
        return set()
    if not isinstance(payload, dict):
        print(f"[WARN] Formato invalido en '{lock_path}': se esperaba objeto JSON.", file=sys.stderr)
        return set()
    files_entry = payload.get("files")
    if files_entry is None:
        return set()
    if not isinstance(files_entry, dict):
        print(f"[WARN] Formato invalido en '{lock_path}': 'files' debe ser un objeto.", file=sys.stderr)
        return set()
    return {_normalize_rel_path(key) for key in files_entry if isinstance(key, str) and key.strip()}


def _infer_base_dir(rel_path: str, file_path: pathlib.Path) -> pathlib.Path | None:
    parts = pathlib.PurePosixPath(rel_path).parts
    if not parts or "." in parts or ".." in parts or len(file_path.parts) < len(parts):
        return None
    return file_path.parents[len(parts) - 1] if file_path.parts[-len(parts) :] == parts else None


def is_syncable_framework_file(
    rel_path: str, file_path: pathlib.Path, managed_lock_paths: set[str] | None = None
) -> bool:
    """Return True if `rel_path` belongs to core framework and is not generator-managed."""
    norm_rel = _normalize_rel_path(rel_path)
    if norm_rel in EXCLUDE_EXACT or norm_rel.startswith(".agents/overrides/") or norm_rel.endswith(".pyc") or "__pycache__" in norm_rel:
        return False
    effective_lock = managed_lock_paths
    if effective_lock is None:
        inferred = _infer_base_dir(norm_rel, file_path)
        effective_lock = load_managed_lock_paths(inferred) if inferred is not None else set()
    if norm_rel in effective_lock:
        return False
    if file_path.exists() and file_path.is_file():
        try:
            with file_path.open("r", encoding="utf-8", errors="ignore") as handle:
                if GENERATED_MARKER in handle.read(GENERATED_PREVIEW_CHARS):
                    return False
        except OSError as exc:
            print(f"[WARN] No se pudo inspeccionar '{file_path}': {exc}", file=sys.stderr)
    return (
        any(norm_rel == b or norm_rel.startswith(f"{b}/") for b in FRAMEWORK_PATHS)
        or norm_rel in CORE_AGENT_FILES
        or any(norm_rel.startswith(p) for p in CORE_RULE_PREFIXES)
        or norm_rel.startswith(".agents/skills/")
    )


def _could_contain_framework_files(rel_dir: str) -> bool:
    if rel_dir in {".agents", ".sdd", ".github", "docs", "specs"} or rel_dir.startswith((".agents/agents", ".agents/rules", ".agents/skills")):
        return True
    return any(rel_dir == b or rel_dir.startswith(f"{b}/") for b in FRAMEWORK_PATHS if b != "specs/SDD_FRAMEWORK.md")


def get_all_framework_files(base_dir: pathlib.Path) -> set[str]:
    """Collect all syncable framework-relative paths under `base_dir` safely."""
    base_resolved = _validate_root_dir(base_dir, "Workspace directory")
    managed_lock_paths = load_managed_lock_paths(base_resolved)
    files: set[str] = set()
    for root, dirnames, filenames in os.walk(base_resolved, followlinks=False):
        root_path = pathlib.Path(root)
        kept_dirs: list[str] = []
        for dname in sorted(dirnames):
            if dname in IGNORED_WALK_DIRS:
                continue
            dir_full = root_path / dname
            rel_dir = dir_full.relative_to(base_resolved).as_posix()
            if _could_contain_framework_files(rel_dir) and _is_reparse_or_symlink(dir_full):
                raise SyncSecurityError(f"Symlink/reparse point directory not permitted: {rel_dir}")
            if not _is_reparse_or_symlink(dir_full):
                kept_dirs.append(dname)
        dirnames[:] = kept_dirs
        for fname in sorted(filenames):
            full_path = root_path / fname
            rel = full_path.relative_to(base_resolved).as_posix()
            if is_syncable_framework_file(rel, full_path, managed_lock_paths=managed_lock_paths):
                _resolve_safe_member(base_resolved, rel)
                files.add(rel)
    return files


def _load_sync_state(target_root: pathlib.Path) -> dict[str, str]:
    state_path = target_root / SYNC_STATE_REL_PATH
    if _is_reparse_or_symlink(state_path):
        raise SyncSecurityError(f"Sync state file must not be a symlink: {SYNC_STATE_REL_PATH}")
    if not state_path.exists():
        return {}
    try:
        payload = json.loads(state_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise SyncConfigError(f"Corrupt sync state file '{state_path}': {exc}") from exc
    if not isinstance(payload, dict) or payload.get("schema_version") != 1:
        raise SyncConfigError(f"Invalid sync state schema in '{state_path}'.")
    files = payload.get("files")
    if not isinstance(files, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in files.items()):
        raise SyncConfigError(f"Invalid 'files' mapping in sync state '{state_path}'.")
    return dict(files)


def _prepare_payload(src_file: pathlib.Path, *, sanitize: bool) -> bytes:
    content = src_file.read_bytes()
    if not sanitize:
        return content
    try:
        text = content.decode("utf-8")
        return text.replace("P.A.C.O.", "Project").replace("PACO", "Project").replace("@jarvis", "@orchestrator").encode("utf-8")
    except UnicodeDecodeError:
        return content


def _compute_sync_plan(
    direction: str, producer_root: pathlib.Path, consumer_root: pathlib.Path, *, sanitize: bool, dry_run: bool
) -> tuple[SyncPlan, dict[str, bytes], dict[str, str]]:
    src_files, prior_state = get_all_framework_files(producer_root), _load_sync_state(consumer_root)
    added, updated, conflicts, skipped = [], [], [], []
    payloads: dict[str, bytes] = {}
    desired_hashes: dict[str, str] = {}
    for rel in sorted(src_files):
        src_file = _resolve_safe_member(producer_root, rel)
        dst_file = _resolve_safe_member(consumer_root, rel)
        new_bytes = _prepare_payload(src_file, sanitize=sanitize)
        payloads[rel] = new_bytes
        desired_hashes[rel] = hashlib.sha256(new_bytes).hexdigest()
        if not dst_file.exists():
            added.append(rel)
        elif not dst_file.is_file():
            conflicts.append(rel)
        else:
            dst_bytes = dst_file.read_bytes()
            if dst_bytes == new_bytes:
                skipped.append(rel)
            elif prior_state.get(rel) == hashlib.sha256(dst_bytes).hexdigest():
                updated.append(rel)
            else:
                conflicts.append(rel)
    plan = SyncPlan(
        direction=direction, source_root=producer_root, target_root=consumer_root,
        added=tuple(added), updated=tuple(updated), conflicts=tuple(conflicts),
        skipped=tuple(skipped), applied=False, dry_run=dry_run,
    )
    return plan, payloads, desired_hashes


def _print_sync_plan(plan: SyncPlan, *, force: bool) -> None:
    tag = "[DRY-RUN] " if plan.dry_run else ""
    print(f"{tag}Plan ({plan.direction}): {plan.source_root} -> {plan.target_root}")
    for rel in plan.added:
        print(f"  + [ADD] {rel}")
    for rel in plan.updated:
        print(f"  ~ [UPDATE] {rel}")
    for rel in plan.conflicts:
        print(f"  ! [CONFLICT] {rel} ({'forced overwrite' if force else 'manual divergence / unexpected diff'})")
    for rel in plan.skipped[:20]:
        print(f"  = [SKIP] {rel}")
    if len(plan.skipped) > 20:
        print(f"  = [SKIP] ... ({len(plan.skipped) - 20} additional identical file(s))")
    print(f"{tag}Summary: add={len(plan.added)} update={len(plan.updated)} conflict={len(plan.conflicts)} skip={len(plan.skipped)}")


def _restore_sync_backups(
    backed_up: list[tuple[pathlib.Path, pathlib.Path]],
    created_files: list[pathlib.Path],
    created_dirs: list[pathlib.Path],
) -> None:
    for created in reversed(created_files):
        if created.is_file() or created.is_symlink():
            created.unlink()
    for dst_file, bak_file in reversed(backed_up):
        dst_file.parent.mkdir(parents=True, exist_ok=True)
        with dst_file.open("wb") as handle:
            handle.write(bak_file.read_bytes())
    for d in reversed(created_dirs):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()


def _track_and_mkdir(parent: pathlib.Path, root: pathlib.Path, created_dirs: list[pathlib.Path]) -> None:
    missing: list[pathlib.Path] = []
    cur = parent
    while cur != root and not cur.exists():
        missing.append(cur)
        cur = cur.parent
    for d in reversed(missing):
        d.mkdir(exist_ok=True)
        if d not in created_dirs:
            created_dirs.append(d)


def _apply_sync_transaction(
    consumer_root: pathlib.Path, writes: list[tuple[str, bytes]], state_bytes: bytes | None
) -> None:
    all_entries = [*writes, *(([(SYNC_STATE_REL_PATH.as_posix(), state_bytes)]) if state_bytes is not None else [])]
    if not all_entries:
        return
    with tempfile.TemporaryDirectory(prefix="sdd-sync-tx-") as tmp_str:
        tmp_root = pathlib.Path(tmp_str)
        stage_dir, backup_dir = tmp_root / "stage", tmp_root / "backup"
        stage_dir.mkdir()
        backup_dir.mkdir()
        tx_items, backed_up, created_files, created_dirs = [], [], [], []
        for rel, data in all_entries:
            staged_file = stage_dir / rel
            staged_file.parent.mkdir(parents=True, exist_ok=True)
            staged_file.write_bytes(data)
            dst_file = _resolve_safe_member(consumer_root, rel)
            if dst_file.is_file():
                bak_file = backup_dir / rel
                bak_file.parent.mkdir(parents=True, exist_ok=True)
                bak_file.write_bytes(dst_file.read_bytes())
                backed_up.append((dst_file, bak_file))
            elif not dst_file.exists():
                created_files.append(dst_file)
            tx_items.append((staged_file, dst_file))
        try:
            for staged_file, dst_file in tx_items:
                _track_and_mkdir(dst_file.parent, consumer_root, created_dirs)
                if dst_file.is_dir():
                    raise IsADirectoryError(f"Destination path is a directory, expected file: {dst_file}")
                shutil.copy2(staged_file, dst_file)
        except BaseException:
            _restore_sync_backups(backed_up, created_files, created_dirs)
            raise


def _execute_sync(
    direction: str, producer_root: pathlib.Path, consumer_root: pathlib.Path,
    *, sanitize: bool, dry_run: bool, force: bool,
) -> SyncPlan:
    producer = _validate_root_dir(producer_root, "Source directory")
    consumer = _validate_root_dir(consumer_root, "Destination directory")
    if producer == consumer:
        raise SyncConfigError(f"Source and destination directories must be distinct: {producer}")
    plan, payloads, desired_hashes = _compute_sync_plan(direction, producer, consumer, sanitize=sanitize, dry_run=dry_run)
    _print_sync_plan(plan, force=force)
    if dry_run:
        return plan
    if plan.conflicts and not force:
        raise SyncConflictError(
            f"Aborted {direction}: destination conflict(s) detected ({', '.join(plan.conflicts)}). "
            "Re-run with --force / --allow-overwrite to overwrite."
        )
    targets = sorted([*plan.added, *plan.updated, *(plan.conflicts if force else ())])
    writes = [(rel, payloads[rel]) for rel in targets]
    state_bytes = (json.dumps({"schema_version": 1, "direction": direction, "files": desired_hashes}, indent=2, sort_keys=True) + "\n").encode("utf-8")
    existing_state = consumer / SYNC_STATE_REL_PATH
    state_to_write = None if (existing_state.is_file() and existing_state.read_bytes() == state_bytes) else state_bytes
    _apply_sync_transaction(consumer, writes, state_to_write)
    print(f"\n[OK] Sincronizacion '{direction}' completada: {len(writes)} fichero(s) aplicados.")
    return replace(plan, applied=True, dry_run=False)


def compare_framework(source_root: pathlib.Path, template_root: pathlib.Path | None = None) -> None:
    """Compare syncable framework files between project root and template root."""
    src_dir = _validate_root_dir(source_root, "Source directory")
    tpl_dir = resolve_template_root(template_root, source_root=src_dir)
    src_files, tpl_files = get_all_framework_files(src_dir), get_all_framework_files(tpl_dir)
    identical, modified, only_src, only_tpl = [], [], [], []
    for rel in sorted(src_files | tpl_files):
        f_src, f_tpl = _resolve_safe_member(src_dir, rel), _resolve_safe_member(tpl_dir, rel)
        if f_src.exists() and f_tpl.exists():
            (identical if filecmp.cmp(f_src, f_tpl, shallow=False) else modified).append(rel)
        else:
            (only_src if f_src.exists() else only_tpl).append(rel)
    print("=== ESTADO DE SINCRONIZACION DEL FRAMEWORK SDD ===")
    print(f"Origen (Proyecto Actual): {src_dir}\nDestino (Plantilla SDD) : {tpl_dir}\n")
    for title, items, marker in (("[MODIFICADOS / DIVERGENTES]:", modified, "*"), ("[NUEVOS EN ESTE PROYECTO]:", only_src, "+"), ("[SOLO EN LA PLANTILLA]:", only_tpl, "-")):
        if items:
            print(title, *(f"  {marker} {i}" for i in items), "", sep="\n")
    if not modified and not only_src and not only_tpl:
        print("[OK] Todos los componentes del framework estan 100% sincronizados.\n")
    else:
        print(f"Total: {len(identical)} identicos, {len(modified)} modificados, {len(only_src)} solo en proyecto, {len(only_tpl)} solo en plantilla.\n")


def push_to_template(
    source_root: pathlib.Path, template_root: pathlib.Path | None = None, *, dry_run: bool = False, force: bool = False
) -> SyncPlan:
    """Export sanitized framework files from `source_root` to `template_root`."""
    src_dir = _validate_root_dir(source_root, "Source directory")
    tpl_dir = resolve_template_root(template_root, source_root=src_dir)
    return _execute_sync("push", src_dir, tpl_dir, sanitize=True, dry_run=dry_run, force=force)


def pull_from_template(
    source_root: pathlib.Path, template_root: pathlib.Path | None = None, *, dry_run: bool = False, force: bool = False
) -> SyncPlan:
    """Import framework files from `template_root` into `source_root` safely."""
    proj_dir = _validate_root_dir(source_root, "Project directory")
    tpl_dir = resolve_template_root(template_root, source_root=proj_dir)
    return _execute_sync("pull", tpl_dir, proj_dir, sanitize=False, dry_run=dry_run, force=force)


def _resolve_cli_template(args: argparse.Namespace, current_root: pathlib.Path, explicit: str | None) -> pathlib.Path:
    exp = explicit.strip() if isinstance(explicit, str) and explicit.strip() else None
    tdir = args.template_dir.strip() if isinstance(args.template_dir, str) and args.template_dir.strip() else None
    if exp and tdir and _validate_root_dir(exp, "Explicit template directory") != _validate_root_dir(tdir, "--template-dir"):
        raise SyncConfigError(f"Conflicting template paths supplied: {exp} != {tdir}")
    return resolve_template_root(exp or tdir, source_root=current_root)


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint for SDD framework synchronization."""
    parser = argparse.ArgumentParser(description="SDD Framework Bi-Directional Synchronizer")
    parser.add_argument("--template-dir", type=str, default=None, help=f"Ruta plantilla SDD (o env {TEMPLATE_DIR_ENV_VAR})")
    parser.add_argument("--dry-run", action="store_true", help="Previsualiza cambios y conflictos sin escribir en disco")
    parser.add_argument("--force", "--allow-overwrite", dest="force", action="store_true", help="Permite sobrescribir conflictos")
    group = parser.add_mutually_exclusive_group(required=False)
    group.add_argument("--status", action="store_true", help="Muestra divergencia y estado entre proyecto y plantilla")
    group.add_argument("--push-to-template", nargs="?", const="", default=None, metavar="PATH", help="Exporta mejoras a plantilla")
    group.add_argument("--pull-from-template", nargs="?", const="", default=None, metavar="PATH", help="Incorpora mejoras desde plantilla")
    args = parser.parse_args(argv)
    current_root = pathlib.Path(__file__).resolve().parents[1]
    try:
        if args.push_to_template is not None:
            push_to_template(current_root, _resolve_cli_template(args, current_root, args.push_to_template), dry_run=args.dry_run, force=args.force)
        elif args.pull_from_template is not None:
            pull_from_template(current_root, _resolve_cli_template(args, current_root, args.pull_from_template), dry_run=args.dry_run, force=args.force)
        else:
            compare_framework(current_root, _resolve_cli_template(args, current_root, None))
    except (SddSyncError, OSError) as exc:
        print(f"[ERROR SDD] {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
