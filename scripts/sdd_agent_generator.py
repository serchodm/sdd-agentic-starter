@dataclass(frozen=True)
class WorkspacePaths:
    """Resolved workspace directory and file layout rooted at `repo_root`."""
    root: pathlib.Path; agents_dir: pathlib.Path; overrides_dir: pathlib.Path; inbox_dir: pathlib.Path
    pack_rules_dir: pathlib.Path; skills_dir: pathlib.Path; stack_path: pathlib.Path; lock_file: pathlib.Path
    archetypes_dir: pathlib.Path; specialists_dir: pathlib.Path; packs_dir: pathlib.Path

    @classmethod
    def from_root(cls, repo_root: pathlib.Path | None = None) -> WorkspacePaths:
        root = (repo_root or ROOT_DIR).resolve()
        ag, cat = root / ".agents", root / ".sdd" / "catalog"
        return cls(
            root, ag / "agents", ag / "overrides", root / ".agent-inbox", ag / "pack-rules", ag / "skills",
            root / "specs" / "STACK.md", ag / "squad.lock.json", cat / "archetypes", cat / "specialists", cat / "packs",
        )

@dataclass(frozen=True)
class PlannedFile:
    """Single deterministic file planned for preflight check and write."""
    rel_path: str; content: bytes; sha256: str; owner: str; kind: Literal["agent", "skill", "rule", "workflow"]

def _normalize_lf(text: str) -> str:
    return text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")

def _read_utf8(path: pathlib.Path, error_cls: type[SddGeneratorError] = InvalidManifestError) -> str:
    try: return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc: raise error_cls(f"Cannot read UTF-8 file '{path}': {exc}") from exc

def _read_bytes(path: pathlib.Path) -> bytes:
    try: return path.read_bytes()
    except OSError as exc: raise InvalidManifestError(f"Cannot read asset '{path}': {exc}") from exc

def _resolve_repo_rel_path(repo_root: pathlib.Path, rel_path: str) -> pathlib.Path:
    if not rel_path or "\\" in rel_path or "\x00" in rel_path:
        raise InvalidManifestError(f"Invalid POSIX repo-relative path: {rel_path!r}.")
    posix = pathlib.PurePosixPath(rel_path)
    if posix.is_absolute() or ".." in posix.parts:
        raise InvalidManifestError(f"Path traversal not permitted: {rel_path!r}.")
    root_resolved = repo_root.resolve()
    target = (root_resolved / posix).resolve()
    if not target.is_relative_to(root_resolved) or target == root_resolved:
        raise InvalidManifestError(f"Target path escapes repository root: {rel_path!r}.")
    return target

def inject_generated_header(content: str, marker: str) -> str:
    """Insert GENERATED HTML comment after YAML frontmatter if present, else on line 1."""
    clean = marker.strip()
    comment = (f"<!-- {GENERATED_MARKER} ({clean}). Do not edit directly. -->" if GENERATED_MARKER not in clean
               else (clean if clean.startswith("<!--") else f"<!-- {clean} -->"))
    lines = _normalize_lf(content).split("\n")
    if lines and lines[0].rstrip() == "---":
        if (close_idx := next((i for i in range(1, len(lines)) if lines[i].rstrip() == "---"), None)) is not None:
            before, after = "\n".join(lines[: close_idx + 1]), "\n".join(lines[close_idx + 1 :])
            return f"{before}\n{comment}\n{after}" if after else f"{before}\n{comment}\n"
    normalized = "\n".join(lines)
    return f"{comment}\n{normalized}" if normalized else f"{comment}\n"

def ensure_inbox(agent_name: str, inbox_dir: pathlib.Path = INBOX_DIR) -> None:
    """Ensure `.agent-inbox/<agent_name>/.gitkeep` exists inside `inbox_dir`."""
    base = inbox_dir.resolve()
    agent_inbox = (base / agent_name).resolve()
    if not agent_inbox.is_relative_to(base) or agent_inbox == base:
        raise InvalidManifestError(f"Invalid agent inbox name: {agent_name!r}.")
    agent_inbox.mkdir(parents=True, exist_ok=True)
    if not (gitkeep := agent_inbox / ".gitkeep").exists():
        gitkeep.touch()

def compile_builder_agent(
    builder: Mapping[str, object], tech_stack: str, overrides_dir: pathlib.Path = OVERRIDES_DIR, archetypes_dir: pathlib.Path = ARCHETYPES_DIR,
) -> str:
    """Compile a builder agent markdown document from override or archetype template."""
    agent_name, archetype_name = str(builder["name"]), str(builder.get("archetype", "tier-backend"))
    overrides_root, override_path = overrides_dir.resolve(), (overrides_dir.resolve() / f"{agent_name}.md").resolve()
    if override_path.is_relative_to(overrides_root) and override_path.is_file():
        print(f"  -> [OVERRIDE] Aplicando override especifico de proyecto: {override_path.name}")
        raw = _normalize_lf(_read_utf8(override_path, SddGeneratorError))
        return raw if GENERATED_MARKER in raw[:4096] else inject_generated_header(
            raw, f"<!-- {GENERATED_MARKER} (builder:{agent_name}, override). Do not edit directly; use .agents/overrides/{agent_name}.md -->"
        )
    search_dir = archetypes_dir if archetypes_dir.is_dir() else ARCHETYPES_DIR
    search_root = search_dir.resolve()
    archetype_file = next((c for n in (f"{archetype_name}.archetype.md", "tier-backend.archetype.md")
                           if (c := (search_root / n).resolve()).is_relative_to(search_root) and c.is_file()), None)
    if archetype_file is None:
        raise SddGeneratorError(f"Builder archetype '{archetype_name}' not found in '{search_dir}'.")
    template = _normalize_lf(_read_utf8(archetype_file, SddGeneratorError))
    raw_zones = builder.get("zone_paths", ())
    zones = [str(p) for p in raw_zones] if isinstance(raw_zones, Sequence) and not isinstance(raw_zones, (str, bytes)) else []
    compiled = (
        template.replace("{{AGENT_NAME}}", agent_name).replace("{{ZONE_PATHS}}", "\n".join(f"  - `{p}`" for p in zones))
        .replace("{{TECH_STACK}}", tech_stack).replace("{{DOD_COMMAND}}", str(builder.get("dod", "test command")))
        .replace("{{FORBIDDEN_IMPORTS}}", str(builder.get("forbidden", "None")))
    )
    return inject_generated_header(compiled, f"<!-- {GENERATED_MARKER} (builder:{agent_name}) from archetype '{archetype_name}'. Do not edit directly; use .agents/overrides/{agent_name}.md -->")

def _iter_skill_files(skill_dir: pathlib.Path) -> list[tuple[str, pathlib.Path]]:
    """Walk `skill_dir` recursively, skipping `__pycache__`/`.pyc` and escaping symlinks."""
    skill_root, collected, seen_dirs = skill_dir.resolve(), [], {skill_dir.resolve()}
    def _walk(current: pathlib.Path) -> None:
        for entry in sorted(current.iterdir(), key=lambda p: p.name):
            if entry.name == "__pycache__" or entry.suffix == ".pyc": continue
            resolved = entry.resolve()
            if not resolved.is_relative_to(skill_root): raise InvalidManifestError(f"Skill asset escapes skill directory '{skill_dir.name}': {entry}.")
            if entry.is_symlink() and not entry.exists(): raise InvalidManifestError(f"Broken symlink in skill directory '{skill_dir.name}': {entry}.")
            if entry.is_dir():
                if resolved in seen_dirs: raise InvalidManifestError(f"Cyclic directory symlink in skill '{skill_dir.name}': {entry}.")
                seen_dirs.add(resolved); _walk(entry)
            elif entry.is_file(): collected.append((entry.relative_to(skill_root).as_posix(), resolved))
    _walk(skill_root)
    return collected

def _verif_commands_mapping(cmds: VerificationCommands) -> dict[str, str]:
    """Flatten `VerificationCommands` into key/alias -> command strings for `sdd_ownership`."""
    return {key: str(val) for attr, keys in _VERIF_SLOT_ALIASES.items() if (val := getattr(cmds, attr)) for key in keys}

def _resolve_builders(
    paths: WorkspacePaths, preset: str, verif_cmds: VerificationCommands, gate_s0_approved: bool, *, warn_unowned: bool = True,
) -> list[BuilderSpec]:
    """Compile builders from `sdd:ownership-map` (with preset fallback) and enforce §2.5 DoD commands."""
    verif_map = _verif_commands_mapping(verif_cmds)
    if (ownership_cfg := parse_ownership_map(paths.stack_path)) is not None:
        if ownership_cfg.preset is not None and ownership_cfg.preset not in PRESET_CONFIGS:
            raise StackConfigError(f"Unknown preset {ownership_cfg.preset!r} in sdd:ownership-map.")
        coverage_warnings = validate_repo_coverage(ownership_cfg, paths.root)
        if warn_unowned:
            for warning in coverage_warnings: print(f"  -> [WARN] {warning}", file=sys.stderr)
        resolved: list[BuilderSpec] = []
        for raw_b in sorted(compile_ownership_builders(ownership_cfg, verif_map), key=lambda item: str(item["name"])):
            name, raw_dod = str(raw_b["name"]), str(raw_b.get("dod", "")).strip()
            if override := verif_cmds.builders.get(name): dod = override
            elif not raw_dod or raw_dod == _OWNERSHIP_DEFAULT_DOD or (raw_dod in _ALL_SLOT_KEYS and raw_dod not in verif_map):
                dod = resolve_builder_dod(name, "test command", verif_cmds, gate_s0_approved=gate_s0_approved)
            elif is_generic_dod_placeholder(raw_dod):
                dod = resolve_builder_dod(name, raw_dod, verif_cmds, gate_s0_approved=gate_s0_approved)
            else: dod = raw_dod
            resolved.append(_b(name, str(raw_b["archetype"]), list(raw_b["zone_paths"]), dod, str(raw_b.get("forbidden", "None"))))
        return resolved
    return sorted(
        (_b(b["name"], b["archetype"], list(b["zone_paths"]), resolve_builder_dod(b["name"], b["dod"], verif_cmds, gate_s0_approved=gate_s0_approved), b["forbidden"])
         for b in PRESET_CONFIGS[preset]["builders"]),
        key=lambda item: item["name"],
    )

def _build_materialization_plan(
    paths: WorkspacePaths, builders: Sequence[BuilderSpec], tech_stack: str, resolved_packs: Sequence[ResolvedPackAssets]
) -> tuple[dict[str, PlannedFile], list[str], list[str], list[str]]:
    desired: dict[str, PlannedFile] = {}
    def add(rel: str, data: bytes, owner: str, kind: Literal["agent", "skill", "rule", "workflow"]) -> None:
        if rel in desired: raise CollisionError(f"Materialization collision on '{rel}' between '{desired[rel].owner}' and '{owner}'.")
        desired[rel] = PlannedFile(rel, data, hashlib.sha256(data).hexdigest(), owner, kind)
    def asset_bytes(src: pathlib.Path, marker: str) -> bytes:
        return _normalize_lf(inject_generated_header(_read_utf8(src), marker)).encode("utf-8") if src.suffix.lower() == ".md" else _read_bytes(src)

    builder_names = sorted(b["name"] for b in builders)
    for b in sorted(builders, key=lambda item: item["name"]):
        add(f".agents/agents/{b['name']}.md", _normalize_lf(compile_builder_agent(b, tech_stack, paths.overrides_dir, paths.archetypes_dir)).encode("utf-8"), f"builder:{b['name']}", "agent")
    specialist_names: list[str] = []
    if paths.specialists_dir.exists():
        if not paths.specialists_dir.is_dir(): raise InvalidManifestError(f"Specialists path is not a directory: {paths.specialists_dir}.")
        spec_root, spec_marker = paths.specialists_dir.resolve(), f"<!-- {GENERATED_MARKER} (specialists). Do not edit directly. -->"
        for sf in sorted(paths.specialists_dir.glob("*.md"), key=lambda p: p.name):
            if not (res := sf.resolve()).is_relative_to(spec_root) or not res.is_file():
                raise InvalidManifestError(f"Invalid universal specialist path: '{sf}'.")
            add(f".agents/agents/{sf.name}", asset_bytes(res, spec_marker), "specialists", "agent"); specialist_names.append(sf.stem)
    pack_agent_names: list[str] = []
    for assets in resolved_packs:
        pack_name = assets.manifest.dir_name
        owner, marker = f"pack:{pack_name}", f"<!-- {GENERATED_MARKER} (pack:{pack_name}). Do not edit directly. -->"
        for af in assets.agent_files:
            add(f".agents/agents/{af.name}", asset_bytes(af, marker), owner, "agent"); pack_agent_names.append(af.stem)
        for slug, skill_dir in assets.skill_dirs:
            for rel_posix, src in _iter_skill_files(skill_dir):
                add(f".agents/skills/{slug}/{rel_posix}", asset_bytes(src, marker), owner, "skill")
        for src_files, prefix, kind in ((assets.rule_files, f".agents/pack-rules/{pack_name}", "rule"), (assets.workflow_files, ".agents/workflows", "workflow")):
            for src in src_files: add(f"{prefix}/{src.name}", asset_bytes(src, marker), owner, kind)
    return desired, builder_names, sorted(specialist_names), sorted(pack_agent_names)

def _prepare_plan(
    paths: WorkspacePaths, preset_name: str | None = None, requested_packs: Sequence[str] | None = None, *, warn_unowned: bool = True,
) -> tuple[StackConfig, bool, str, tuple[PackActivation, ...], dict[str, PlannedFile], list[str], list[str], list[str]]:
    config, effective_gate_s0 = parse_stack_config(paths.stack_path, valid_presets=PRESET_CONFIGS.keys())
    effective_preset = preset_name if preset_name is not None else config.preset
    if effective_preset not in PRESET_CONFIGS:
        raise StackConfigError(f"Unknown preset {effective_preset!r}; expected one of: {', '.join(sorted(PRESET_CONFIGS))}.")
    verif_cmds = parse_verification_commands(paths.stack_path)
    activations, resolved_packs = resolve_active_packs(config, effective_gate_s0, requested_packs, paths.packs_dir, effective_preset=effective_preset)
    builders = _resolve_builders(paths, effective_preset, verif_cmds, effective_gate_s0, warn_unowned=warn_unowned)
    desired, builder_names, specialist_names, pack_agents = _build_materialization_plan(paths, builders, DEFAULT_TECH_STACK, resolved_packs)
    return config, effective_gate_s0, effective_preset, activations, desired, builder_names, specialist_names, pack_agents

def _load_previous_lock(lock_file: pathlib.Path, repo_root: pathlib.Path) -> tuple[dict[str, object] | None, dict[str, dict[str, str]], set[str]]:
    if not lock_file.exists() and not lock_file.is_symlink(): return None, {}, set()
    if lock_file.is_symlink() or not lock_file.is_file():
        raise ManualModificationConflictError(f"Lock file must be a regular file (not symlink): '{lock_file}'.")
    try: payload = json.loads(lock_file.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise InvalidManifestError(f"Invalid or unreadable lock file '{lock_file}': {exc}") from exc
    if not isinstance(payload, dict): raise InvalidManifestError(f"Lock file root must be a JSON object: '{lock_file}'.")
    prev_files: dict[str, dict[str, str]] = {}
    if (raw_files := payload.get("files")) is not None:
        if not isinstance(raw_files, dict): raise InvalidManifestError(f"Field 'files' in '{lock_file}' must be a JSON object.")
        for rel, meta in raw_files.items():
            if not isinstance(rel, str): raise InvalidManifestError(f"Invalid file key in '{lock_file}': {rel!r}.")
            _resolve_repo_rel_path(repo_root, rel)
            if not isinstance(meta, dict) or not isinstance(meta.get("sha256"), str) or not meta["sha256"].strip():
                raise InvalidManifestError(f"Corrupt lock metadata for '{rel}' in '{lock_file}'.")
            prev_files[rel] = {"sha256": meta["sha256"], "owner": str(meta.get("owner", "")), "kind": str(meta.get("kind", ""))}
    prev_agents: set[str] = set()
    for key in ("core_agents", "builders", "specialists"):
        if (entries := payload.get(key)) is not None:
            if not isinstance(entries, list) or any(not isinstance(x, str) or not x.strip() for x in entries):
                raise InvalidManifestError(f"Field '{key}' in '{lock_file}' must be a list of non-empty strings.")
            prev_agents.update(entries)
    prev_agents.update(pathlib.PurePosixPath(r).stem for r, m in prev_files.items() if m["kind"] == "agent" or (r.startswith(".agents/agents/") and r.endswith(".md")))
    return payload, prev_files, prev_agents

def _preflight_check(paths: WorkspacePaths, desired: Mapping[str, PlannedFile], prev_files: Mapping[str, Mapping[str, str]]) -> None:
    for rel, planned in sorted(desired.items()):
        disk = _resolve_repo_rel_path(paths.root, rel)
        for anc in disk.parents:
            if anc == paths.root: break
            if anc.exists() and not anc.is_dir():
                raise CollisionError(f"Unmanaged file blocks directory '{anc.relative_to(paths.root).as_posix()}' for '{rel}'.")
        if disk.exists() or disk.is_symlink():
            if rel not in prev_files:
                raise CollisionError(f"Unmanaged destination already exists on disk: '{rel}' (planned by '{planned.owner}').")
            if disk.is_symlink() or not disk.is_file():
                raise ManualModificationConflictError(f"Manual modification conflict on '{rel}': expected regular managed file.")
            if hashlib.sha256(_read_bytes(disk)).hexdigest() != prev_files[rel]["sha256"]:
                raise ManualModificationConflictError(f"Manual modification conflict on '{rel}': disk SHA-256 differs from lock.")
    for rel, meta in sorted(prev_files.items()):
        if meta.get("owner") == "core": continue
        if rel not in desired and ((disk := _resolve_repo_rel_path(paths.root, rel)).exists() or disk.is_symlink()):
            if disk.is_symlink() or not disk.is_file() or hashlib.sha256(_read_bytes(disk)).hexdigest() != meta["sha256"]:
                raise ManualModificationConflictError(f"Cannot delete '{rel}': file was modified manually since last materialization.")

def materialize_squad(
    preset_name: str | None = None, requested_packs: list[str] | None = None, repo_root: pathlib.Path | None = None,
    *, strict_agents: bool = False, drain_to: str | None = None, fail_on_nonempty_inbox: bool = True, dry_run: bool = False,
) -> dict[str, Any]:
    """Resolve configuration, preflight-check collisions/edits, and transactionally materialize squad."""
    paths = WorkspacePaths.from_root(repo_root)
    _, eff_s0, eff_preset, activations, desired, builders, specialists, pack_agents = _prepare_plan(paths, preset_name, requested_packs)
    prev_payload, prev_files, prev_agents = _load_previous_lock(paths.lock_file, paths.root)
    _preflight_check(paths, desired, prev_files)
    active_agents = [*CORE_AGENTS, *builders, *specialists, *pack_agents]
    lock = build_deterministic_lock_payload(
        stack_approved=eff_s0, preset=eff_preset, tech_stack=DEFAULT_TECH_STACK, core_agents=CORE_AGENTS,
        builders=builders, specialists=specialists, active_packs=activations, files=desired,
        core_agent_files=collect_core_agent_files(paths.agents_dir, CORE_AGENTS), prev_payload=prev_payload,
    )
    if dry_run:
        if strict_agents: detect_orphan_agents(paths.agents_dir, active_agents, strict=True, prev_managed_agents=prev_agents)
        print(f"[DRY-RUN] Plan valido: preset={eff_preset}, gate_s0={eff_s0}, files={len(desired)}")
        return lock
    canonical_bytes = (json.dumps(lock, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    needs_write = not paths.lock_file.is_file() or paths.lock_file.is_symlink() or _read_bytes(paths.lock_file) != canonical_bytes
    tx_summary = apply_plan_transactionally(
        paths, desired, prev_files, active_agents, prev_agents, lock_payload=lock, write_lock=needs_write,
        drain_to=drain_to, fail_on_nonempty_inbox=fail_on_nonempty_inbox, strict_agents=strict_agents,
    )
    if drain_to is not None:
        extra = reconcile_obsolete_inboxes(paths.inbox_dir, active_agents, drain_to=drain_to, fail_on_nonempty=fail_on_nonempty_inbox)
        tx_summary = [*tx_summary, *(s for s in extra if s not in tx_summary)]
    names = [a.name for a in activations]
    print(f"\n[+] Materializado Escuadron Agentico SDD (preset: {eff_preset}, gate_s0: {eff_s0})")
    print(f"  -> Stack Packs Activos: {', '.join(names) if names else '(Ninguno)'}")
    print(f"  -> Ficheros gestionados: {len(desired)} | Especialistas: {len(specialists)}")
    if tx_summary: print(f"  -> Buzones reconciliados: {', '.join(tx_summary)}")
    print(f"[SUCCESS] Escuadron materializado con exito. Registro actualizado en: {paths.lock_file.name}")
    return lock

def verify_squad(
    preset_name: str | None = None, requested_packs: list[str] | None = None, repo_root: pathlib.Path | None = None, *, strict_agents: bool = True,
) -> list[str]:
    """Read-only verification of `squad.lock.json` integrity, disk files, orphans, and plan."""
    paths = WorkspacePaths.from_root(repo_root)
    _, eff_s0, eff_preset, activations, desired, builders, specialists, _ = _prepare_plan(paths, preset_name, requested_packs, warn_unowned=False)
    expected_meta: dict[str, object] = {
        "stack_approved": eff_s0, "gate00_approved": eff_s0, "preset": eff_preset,
        "builders": sorted(set(builders)), "specialists": sorted(set(specialists)),
        "active_packs": sorted(({"name": a.name, "id": a.pack_id, "source": a.source} for a in activations), key=lambda item: (item["name"], item["id"], item["source"])),
    }
    return verify_lock_integrity(paths, expected_files=desired, expected_meta=expected_meta, core_agents=CORE_AGENTS, strict_agents=strict_agents)

def list_catalog(repo_root: pathlib.Path | None = None) -> None:
    """Print available archetypes, universal specialists, validated packs, and presets."""
    paths = WorkspacePaths.from_root(repo_root)
    print("\n=== ARQUETIPOS EN .sdd/catalog/archetypes/ ===")
    if paths.archetypes_dir.is_dir():
        for f in sorted(paths.archetypes_dir.glob("*.archetype.md")): print(f"  - {f.name.replace('.archetype.md', '')}")
    print("\n=== ESPECIALISTAS UNIVERSALES EN .sdd/catalog/specialists/ ===")
    if paths.specialists_dir.is_dir():
        for f in sorted(paths.specialists_dir.glob("*.md")): print(f"  - @{f.stem}")
    print("\n=== STACK PACKS DISPONIBLES EN .sdd/catalog/packs/ ===")
    for dir_name, manifest in load_catalog_registry(paths.packs_dir).items(): print(f"  - {dir_name} ({manifest.pack_id}): {manifest.description}")
    print("\n=== PRESETS PREDEFINIDOS ===")
    for p_name, p_val in PRESET_CONFIGS.items(): print(f"  * {p_name}: {p_val['description']}")

def main() -> int:
    """CLI entrypoint for squad listing, verification, and transactional materialization."""
    if hasattr(sys.stdout, "reconfigure"):
        try: sys.stdout.reconfigure(encoding="utf-8", errors="replace"); sys.stderr.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, OSError, ValueError) as exc: print(f"[WARN] Could not configure UTF-8 output: {exc}", file=sys.stderr)
    parser = argparse.ArgumentParser(description="SDD Agent Squad Generator & Materializer")
    parser.add_argument("--materialize", action="store_true", help="Materializa el escuadron segun specs/STACK.md")
    parser.add_argument("--verify", action="store_true", help="Verifica integridad de squad.lock.json en modo solo lectura")
    parser.add_argument("--mode", "--preset", dest="mode", choices=list(PRESET_CONFIGS.keys()), help="Preset especifico de escuadron")
    parser.add_argument("--packs", nargs="*", help="Stack packs adicionales a activar")
    parser.add_argument("--strict-agents", action="store_true", help="Falla ante agentes huerfanos no gestionados en .agents/agents/")
    parser.add_argument("--drain-inboxes", nargs="?", const="orchestrator", default=None, metavar="TARGET_AGENT", help="Drena tickets de buzones obsoletos hacia TARGET_AGENT")
    parser.add_argument("--dry-run", action="store_true", help="Valida plan y preflight sin escribir en disco")
    parser.add_argument("--list", action="store_true", help="Muestra el contenido del catalogo y presets")
    args = parser.parse_args()
    try:
        if args.verify and (args.materialize or args.list or args.dry_run):
            raise StackConfigError("--verify is read-only and cannot be combined with --materialize, --dry-run, or --list.")
        if args.list: list_catalog()
        elif args.verify:
            if mismatches := verify_squad(preset_name=args.mode, requested_packs=args.packs, strict_agents=True):
                for err in mismatches: print(f"[ERROR SDD] {err}", file=sys.stderr)
                return 1
            print("[OK] squad.lock.json verified cleanly (0 mismatches).")
        elif args.materialize or args.dry_run or args.mode or args.packs is not None:
            materialize_squad(preset_name=args.mode, requested_packs=args.packs, strict_agents=args.strict_agents, drain_to=args.drain_inboxes, dry_run=args.dry_run)
        else: parser.print_help()
    except SddGeneratorError as exc:
        print(f"[ERROR SDD] {exc}", file=sys.stderr); return 1
    return 0

if __name__ == "__main__":
    sys.exit(main())
